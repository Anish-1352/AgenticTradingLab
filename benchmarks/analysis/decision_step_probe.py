#!/usr/bin/env python3
"""Decision-step reliability, measured IN PIPELINE against real upstream context.

    python benchmarks/analysis/decision_step_probe.py --dry-run
    python benchmarks/analysis/decision_step_probe.py --integration openrouter \
        --models nvidia/nemotron-3-nano-30b-a3b deepseek/deepseek-v4-pro -n 4

WHAT PHASE 16 COULD NOT MEASURE, AND WHY
------------------------------------------
Phase 16 ran the decision step in ISOLATED mode: a frozen upstream context
built from the template's own ``outputFormat`` placeholders — right shape, no
real content. Both models returned ``{"orders": []}`` 15/15. Against a signal
object full of placeholder values, "make no trades" is a *reasonable* answer,
so that measured nothing about decision quality and the end-to-end projection
was correctly withheld.

This probe fixes the input, not the model: steps 1 and 2 are actually executed
so step 3 reads a real signal object produced by a real model from real market
data.

THE DESIGN, AND WHY EACH PART OF IT
-------------------------------------
* **Several distinct market regimes.** One snapshot cannot distinguish "this
  model is broken" from "there was nothing to trade". A model that returns no
  orders in a strong-trend regime AND a sell-off is saying something; a model
  that returns none against one flat tape is not.
* **Upstream generated by the CHEAP model.** That is the configuration under
  test. The routing proposal is cheap-on-1-2, expensive-on-3, so the question
  is whether step 3 still works when its input came from the cheap model.
* **Paired.** Every candidate answers the SAME set of real contexts, so a
  difference between models is a difference between models.
* **Contexts generated once and reused.** Regenerating per attempt would let
  upstream variation leak into the between-model comparison.

TWO QUESTIONS, ONLY ONE OF THEM ANSWERABLE HERE
-------------------------------------------------
(a) does the decision step PARSE reliably on each model — measured here.
(b) does it produce the SAME DECISIONS — NOT measured here and not
    approximated. Answering it needs multiple evaluation windows and a
    definition of "same"; one run against four snapshots cannot support it.

THE EMPTY-DECISION RATE IS A RESULT IN ITS OWN RIGHT
------------------------------------------------------
``portfolio_manager.py:432-446`` silently swaps a rule-based decision in when
the model returns no actions, and Phase 17 established that whether this fired
historically is unrecoverable from stored data. It is measurable live, here,
and nowhere else. It is counted separately from parse failures because a
well-formed empty decision is not a model failure — it is a pipeline one.
"""

