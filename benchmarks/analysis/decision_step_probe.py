def _call(client, model: str, prompt: str, max_tokens: int):
    return client.messages.create(
        model=model, max_tokens=max_tokens, system=PIPELINE_SYSTEM_PROMPT,
        messages=[{"role": "user", "content": prompt}])


def build_real_context(client, steps, upstream_model: str, snapshot,
                       max_tokens: int = DEFAULT_MAX_TOKENS,
                       verbose: bool = True) -> Optional[Dict[str, Any]]:
    """Actually run steps 1..N-1 so step N reads a real signal object.

    Returns None when the upstream itself fails — which is a result, not an
    error: a routed pipeline whose cheap upstream cannot produce a signal never
    reaches the decision step at all.
    """
    prior: List[Dict[str, Any]] = []
    tokens_in = tokens_out = 0
    for idx in range(len(steps) - 1):
        prompt = _build_step_prompt(
            step_index=idx, step=steps[idx], market_snapshot=snapshot,
            prior_outputs=prior, is_last=False)
        try:
            resp = _call(client, upstream_model, prompt, max_tokens)
        except Exception as exc:  # noqa: BLE001
            if verbose:
                print(f"      upstream step{idx + 1} api_error: "
                      f"{type(exc).__name__}", flush=True)
            return None
        i_tok, o_tok = extract_token_usage(resp)
        tokens_in += i_tok
        tokens_out += o_tok
        try:
            text = extract_response_text(resp)
        except AttributeError:
            text = ""
        parsed = parse_llm_response(text) if text else None
        if parsed is None:
            if verbose:
                print(f"      upstream step{idx + 1} unparseable; "
                      f"context unusable", flush=True)
            return None
        prior.append({"step": idx + 1,
                      "label": steps[idx].get("label") or f"Step {idx + 1}",
                      "presetKey": steps[idx].get("presetKey"),
                      "id": steps[idx].get("id"), "output": parsed})
    return {"prior_outputs": prior, "upstream_model": upstream_model,
            "upstream_input_tokens": tokens_in,
            "upstream_output_tokens": tokens_out}


def probe_decision_step(client, steps, contexts, model: str, attempts: int,
                        max_tokens: int = DEFAULT_MAX_TOKENS,
                        verbose: bool = True, on_row=None
                        ) -> List[Dict[str, Any]]:
    """``attempts`` decisions per context, for one candidate model."""
    last_idx = len(steps) - 1
    rows = []
    for ctx in contexts:
        prompt = _build_step_prompt(
            step_index=last_idx, step=steps[last_idx],
            market_snapshot=ctx["snapshot"],
            prior_outputs=ctx["prior_outputs"], is_last=True)
        cats, outs, ins, usable = Counter(), [], [], 0
        order_counts = []
        for _ in range(attempts):
            try:
                resp = _call(client, model, prompt, max_tokens)
            except Exception as exc:  # noqa: BLE001
                cats[f"api_error:{type(exc).__name__}"] += 1
                continue
            i_tok, o_tok = extract_token_usage(resp)
            ins.append(i_tok)
            outs.append(o_tok)
            try:
                text = extract_response_text(resp)
            except AttributeError:
                text = ""
            parsed = parse_llm_response(text) if text else None
            ok, cat, _detail = classify_decision(text, parsed)
            cats[cat] += 1
            if ok:
                usable += 1
                dec = pipeline_output_to_decision(parsed) or {}
                order_counts.append(len(dec.get("actions") or []))
        row = {
            "model": model, "regime": ctx["regime"],
            "upstream_model": ctx["upstream_model"],
            "attempts": attempts, "n_usable": usable,
            "parse_rate": usable / attempts if attempts else None,
            "n_empty_orders": cats.get(EMPTY_ORDERS, 0),
            "empty_orders_rate": (cats.get(EMPTY_ORDERS, 0) / attempts
                                  if attempts else None),
            "mean_output_tokens": (sum(outs) / len(outs)) if outs else None,
            "mean_input_tokens": (sum(ins) / len(ins)) if ins else None,
            "mean_orders_when_usable": (
                sum(order_counts) / len(order_counts)) if order_counts else None,
            "categories": dict(cats)}
        rows.append(row)
        if verbose:
            print(f"    {ctx['regime']:<16} {usable}/{attempts} usable  "
                  f"empty={row['n_empty_orders']}  "
                  f"out={row['mean_output_tokens'] or 0:.0f}  {dict(cats)}",
                  flush=True)
        if on_row is not None:
            on_row(row)
    return rows


def rule_of_three_upper_bound(n: int) -> float:
    """95% failure-rate bound after n trials with zero failures. 3/n."""
    if n <= 0:
        raise ValueError("n must be positive")
    return 3.0 / n


def summarise(rows: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Per model, pooled across regimes, with the bound attached."""
    by_model: Dict[str, List[Dict[str, Any]]] = {}
    for r in rows:
        by_model.setdefault(r["model"], []).append(r)

    out = []
    for model, rs in by_model.items():
        n = sum(r["attempts"] for r in rs)
        usable = sum(r["n_usable"] for r in rs)
        empties = sum(r["n_empty_orders"] for r in rs)
        cats: Counter = Counter()
        for r in rs:
            cats.update(r["categories"])
        toks = [r["mean_output_tokens"] for r in rs if r["mean_output_tokens"]]
        rate = usable / n if n else None
        out.append({
            "model": model, "n_total": n, "n_usable": usable,
            "parse_rate": rate,
            "rule_of_three_bound": (rule_of_three_upper_bound(n)
                                    if usable == n else None),
            "n_empty_orders": empties,
            "empty_orders_rate": empties / n if n else None,
            "mean_output_tokens": (sum(toks) / len(toks)) if toks else None,
            "categories": dict(cats),
            "by_regime": {r["regime"]: r["parse_rate"] for r in rs},
        })
    out.sort(key=lambda r: -(r["parse_rate"] or 0))
    return out


