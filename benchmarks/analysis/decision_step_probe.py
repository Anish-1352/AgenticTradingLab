def estimate_ceiling(steps, models, n_regimes, attempts, upstream_model,
                     reuse_contexts: bool = False):
    from analysis.cost_model_lib import PRICE_BY_DB_MODEL  # noqa: PLC0415

    by_slug = {v["slug"]: v for v in PRICE_BY_DB_MODEL.values()}
    # Upstream: (len(steps)-1) calls per regime. Decision: attempts per
    # (regime, model). Input sizes approximated from the template text; output
    # assumed at the cap, which is pessimistic.
    up_price = by_slug.get(upstream_model)
    approx_in = 2500
    total = 0.0
    rows = []
    up_calls = 0 if reuse_contexts else n_regimes * (len(steps) - 1)
    if up_price and up_calls:
        c = up_calls * ((approx_in / 1e6) * up_price["in"]
                        + (DEFAULT_MAX_TOKENS / 1e6) * up_price["out"])
        rows.append({"model": f"{upstream_model} (upstream)", "calls": up_calls,
                     "max_cost_usd": c, "priced": True})
        total += c
    elif up_calls:
        rows.append({"model": f"{upstream_model} (upstream)", "calls": up_calls,
                     "max_cost_usd": None, "priced": False})

    for m in models:
        p = by_slug.get(m)
        calls = n_regimes * attempts
        if not p:
            rows.append({"model": m, "calls": calls, "max_cost_usd": None,
                         "priced": False})
            continue
        c = calls * ((approx_in / 1e6) * p["in"]
                     + (DEFAULT_MAX_TOKENS / 1e6) * p["out"])
        rows.append({"model": m, "calls": calls, "max_cost_usd": c,
                     "priced": True})
        total += c
    return {"rows": rows, "total_max_cost_usd": total,
            "total_calls": up_calls + n_regimes * attempts * len(models),
            "assumption": "output assumed at the max_tokens cap — pessimistic"}


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        description="Decision-step reliability against real upstream context.")
    ap.add_argument("--models", nargs="+",
                    default=["nvidia/nemotron-3-nano-30b-a3b",
                             "deepseek/deepseek-v4-pro"])
    ap.add_argument("--upstream-model", default="nvidia/nemotron-3-nano-30b-a3b",
                    help="model that runs steps 1..N-1 to make the real "
                         "context. Defaults to the cheap model because that IS "
                         "the routed configuration under test.")
    ap.add_argument("-n", "--attempts", type=int, default=4,
                    help="decision attempts per regime per model")
    ap.add_argument("--max-tokens", type=int, default=DEFAULT_MAX_TOKENS)
    ap.add_argument("--integration", default="openrouter")
    ap.add_argument("--template", default=DEFAULT_TEMPLATE)
    ap.add_argument("--out", default=None)
    ap.add_argument("--reuse-contexts", default=None,
                    help="path to a prior results JSON whose upstream contexts "
                         "should be reused verbatim. Keeps the design PAIRED: "
                         "a model added later answers the identical contexts "
                         "earlier models saw, instead of freshly generated "
                         "ones that would confound the comparison.")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--yes", action="store_true")
    return ap


def main(argv: Optional[List[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    steps = load_steps(args.template)
    n_reg = len(REGIMES)
    total_per_model = n_reg * args.attempts
    if total_per_model > 60:
        print(f"refusing {total_per_model} attempts/model: this probe is sized "
              f"for tens.", file=sys.stderr)
        return 2

    est = estimate_ceiling(steps, args.models, n_reg, args.attempts,
                           args.upstream_model,
                           reuse_contexts=bool(args.reuse_contexts))
    print(f"DECISION-STEP PROBE  template={args.template}  "
          f"regimes={n_reg}  attempts/regime={args.attempts}  "
          f"=> {total_per_model} decisions per model")
    if args.reuse_contexts:
        print(f"  upstream: REUSED from {args.reuse_contexts} (no calls)")
    else:
        print(f"  upstream (steps 1-{len(steps) - 1}) by {args.upstream_model}")
    for r in est["rows"]:
        c = f"${r['max_cost_usd']:.4f}" if r["priced"] else "unpriced"
        print(f"  {r['model'][:48]:50s} {r['calls']:>4} calls  max {c}")
    print(f"  {'TOTAL':50s} {est['total_calls']:>4} calls  "
          f"max ${est['total_max_cost_usd']:.4f}  ({est['assumption']})")

    if args.dry_run:
        print("\n--dry-run: nothing called, nothing spent.")
        return 0
    if not args.yes:
        if input(f"\nSpend up to ${est['total_max_cost_usd']:.4f}? [y/N] "
                 ).strip().lower() not in ("y", "yes"):
            print("Aborted; nothing spent.")
            return 1

    from dashboard.backend.infrastructure.llm.providers import (  # noqa: PLC0415
        make_llm_client)
    client = make_llm_client(args.integration)
    if client is None:
        print(f"\nno client for integration={args.integration!r}: its API key "
              f"is not set, so no call was attempted.", file=sys.stderr)
        return 3

    contexts = []
    if args.reuse_contexts:
        with open(args.reuse_contexts, "r", encoding="utf-8") as fh:
            prior = json.load(fh)
        by_regime = {s["_regime"]: s for s in REGIMES}
        for c in prior["contexts"]:
            snap = by_regime.get(c["regime"])
            if snap is None:
                print(f"  skipping unknown regime {c['regime']!r}", flush=True)
                continue
            contexts.append({"prior_outputs": c["prior_outputs"],
                             "upstream_model": c["upstream_model"],
                             "regime": c["regime"], "snapshot": snap})
        print(f"\nreusing {len(contexts)} stored contexts from "
              f"{args.reuse_contexts} (paired; no upstream calls made)")
        for c in contexts:
            sig = json.dumps(c["prior_outputs"][-1]["output"])[:70]
            print(f"  {c['regime']:<16} signal={sig}...", flush=True)

    if not contexts:
        print("\nbuilding real upstream contexts")
    for snap in (REGIMES if not contexts else []):
        ctx = build_real_context(client, steps, args.upstream_model, snap,
                                 args.max_tokens)
        if ctx is None:
            print(f"  {snap['_regime']:<16} UPSTREAM FAILED — "
                  f"decision step never reached", flush=True)
            continue
        sig = json.dumps(ctx["prior_outputs"][-1]["output"])[:80]
        ctx.update(regime=snap["_regime"], snapshot=snap)
        contexts.append(ctx)
        print(f"  {snap['_regime']:<16} ok  signal={sig}...", flush=True)

    if not contexts:
        print("\nno usable contexts: every upstream run failed. That is itself "
              "the result — a routed pipeline with this upstream model never "
              "reaches its decision step.", file=sys.stderr)
        return 4

    all_rows: List[Dict[str, Any]] = []

    def _flush(row=None):
        # Append here rather than after the loop: probe_decision_step
        # accumulates into its own list and only returns at the end, so
        # flushing an outer list alone would write an empty file all run.
        if row is not None:
            all_rows.append(row)
        if not args.out:
            return
        with open(args.out, "w", encoding="utf-8") as fh:
            json.dump({"template": args.template,
                       "upstream_model": args.upstream_model,
                       "attempts_per_regime": args.attempts,
                       "max_tokens": args.max_tokens,
                       "integration": args.integration,
                       "regimes": [c["regime"] for c in contexts],
                       "contexts": [
                           {"regime": c["regime"],
                            "upstream_model": c["upstream_model"],
                            "prior_outputs": c["prior_outputs"]}
                           for c in contexts],
                       "cost_ceiling": est,
                       "rows": all_rows,
                       "summary": summarise(all_rows)}, fh, indent=1)

    for model in args.models:
        print(f"\n  {model}")
        probe_decision_step(client, steps, contexts, model, args.attempts,
                            args.max_tokens, on_row=_flush)
    _flush()

    print("\n" + "=" * 74)
    print(f"{'model':<34}{'usable':>10}{'empty':>9}{'out tok':>9}")
    print("-" * 74)
    for s in summarise(all_rows):
        bound = (f"  (<={s['rule_of_three_bound']:.0%} fail)"
                 if s["rule_of_three_bound"] else "")
        print(f"{s['model'][:32]:<34}{s['n_usable']}/{s['n_total']:<7}"
              f"{s['n_empty_orders']:>9}{s['mean_output_tokens'] or 0:>9.0f}"
              f"{bound}")
    if args.out:
        print(f"\n  wrote {args.out} ({len(all_rows)} rows)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
