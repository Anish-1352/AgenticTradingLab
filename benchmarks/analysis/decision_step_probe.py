# classification
# --------------------------------------------------------------------------


def classify_decision(text: str, parsed: Optional[Dict[str, Any]]
                      ) -> Tuple[bool, str, Optional[str]]:
    """``(usable, category, detail)`` for a decision-step response.

    ``usable`` means production would have CONTINUED with a model decision —
    parsed AND converted to a non-empty action list. An empty-but-well-formed
    decision is reported separately: it is not the model failing, it is the
    pipeline treating a legitimate "no trades" as a failure.
    """
    s = (text or "").strip()
    if not s:
        return False, FAIL_EMPTY, None
    if parsed is None:
        if "{" not in s:
            return False, FAIL_NO_JSON, s[:160]
        if "}" not in s:
            return False, FAIL_TRUNCATED, s[-160:]
        return False, FAIL_MALFORMED, s[:160]
    if not isinstance(parsed, dict):
        return False, FAIL_SCHEMA, type(parsed).__name__

    if pipeline_output_to_decision(parsed) is None:
        for key in ("orders", "actions", "risk_actions"):
            if isinstance(parsed.get(key), list) and not parsed[key]:
                return False, EMPTY_ORDERS, key
        return False, FAIL_SCHEMA, ", ".join(sorted(parsed)[:8]) or "empty object"

    first, last = s.find("{"), s.rfind("}")
    if first > 0 or last < len(s) - 1:
        return True, OK_WRAPPED, None
    return True, OK, None


