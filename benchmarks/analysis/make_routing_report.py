#!/usr/bin/env python3
"""Generate ROUTING_ENDTOEND.md from the measured probes.

    python benchmarks/analysis/make_routing_report.py --check
    python benchmarks/analysis/make_routing_report.py

Every number comes from the committed probe results and load_measured, so the
document cannot drift. A staleness test regenerates and compares byte-for-byte.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from typing import Any, Dict, List, Optional

_HERE = os.path.dirname(os.path.abspath(__file__))
_BENCH_ROOT = os.path.abspath(os.path.join(_HERE, ".."))
if _BENCH_ROOT not in sys.path:
    sys.path.insert(0, _BENCH_ROOT)

from analysis import routing_endtoend as re_  # noqa: E402
from analysis.api_optimisation import (  # noqa: E402
    load_step_measurements, rule_of_three_upper_bound,
)
from analysis.cost_model_lib import load_measured  # noqa: E402
from analysis.tier_check import check_report, format_violations  # noqa: E402

DEFAULT_OUT = os.path.join(_HERE, "ROUTING_ENDTOEND.md")
PROBE = re_.DECISION_PROBE_RESULTS

CHEAP = "nvidia/nemotron-3-nano-30b-a3b"
MID = "deepseek/deepseek-v4-pro"
DEAR = "anthropic/claude-haiku-4-5"

# Phase 18's experiment figures, 1000 agents / 30 days / all seven models.
CADENCE_BILLS = {"hourly (3600s)": 5924.0, "Nof1 (150s)": 142181.0}


def build() -> str:
    measured = load_measured()
    probe = json.load(open(PROBE, "r", encoding="utf-8"))
    dec = re_.load_decision_measurements(PROBE)
    steps_m = load_step_measurements()

    L: List[str] = []
    A = L.append

    A("# Routing, end to end: the decision step measured")
    A("")
    A("Generated by `analysis/make_routing_report.py`. Phase 18 eliminated "
      "output caps (`0.0%` safe reduction) and leaderboard governance (`$0` "
      "recurring) [MEASURED]; prefix caching was already dead. Routing is what "
      "survived, and this closes the gap that blocked its end-to-end number.")
    A("")

    # ------------------------------------------------------------- D1 ------
    A("## What Phase 16 could not measure")
    A("")
    A("Phase 16 ran the decision step in ISOLATED mode against a frozen "
      "upstream context built from `outputFormat` placeholders — right shape, "
      "no content. Both models returned `{\"orders\": []}` `15/15` [MEASURED]. "
      "Against placeholder signals, \"make no trades\" is a reasonable answer, "
      "so that measured nothing about decision quality.")
    A("")
    A(f"This probe runs steps 1-2 for real, so step 3 reads a real signal "
      f"object. Upstream is generated by `{dec['upstream_model']}` — the cheap "
      f"model — because that IS the routed configuration under test. Four "
      f"market regimes, so an all-flat answer is informative rather than "
      f"merely plausible. Every candidate answers the IDENTICAL stored "
      f"contexts, so the comparison is paired [MEASURED].")
    A("")

    A("### Decision-step reliability, in pipeline")
    A("")
    A("| model | usable | empty decisions | out tokens | 95% failure bound | Tier |")
    A("|---|---:|---:|---:|---:|---|")
    for s in probe["summary"]:
        bound = (f"`<={s['rule_of_three_bound']:.0%}`"
                 if s["rule_of_three_bound"] else "—")
        A(f"| `{s['model'].split('/')[-1]}` | "
          f"`{s['n_usable']}/{s['n_total']}` | "
          f"`{s['n_empty_orders']}` | "
          f"`{s['mean_output_tokens'] or 0:,.0f}` | {bound} | MEASURED |")
    A("")
    A("**The empty-decision rate is `0`.** With real upstream context, every "
      "model produced actual orders [MEASURED]. Phase 16's `15/15` empty "
      "result was entirely an artifact of the placeholder fixture, which is "
      "why it could not support a projection. This also means the probe found "
      "no live instance of the `portfolio_manager.py:432-446` silent-fallback "
      "path firing — it remains a real defect, but it did not trigger here.")
    A("")

    A("### The failures are regime-shaped, not uniformly model-shaped")
    A("")
    A("| model | strong_uptrend | sharp_selloff | flat_range | mixed_high_vol | Tier |")
    A("|---|---:|---:|---:|---:|---|")
    by = {}
    for r in probe["rows"]:
        by.setdefault(r["model"], {})[r["regime"]] = r
    for model in [s["model"] for s in probe["summary"]]:
        cells = []
        for reg in ("strong_uptrend", "sharp_selloff", "flat_range",
                    "mixed_high_vol"):
            r = by[model].get(reg)
            cells.append(f"`{r['n_usable']}/{r['attempts']}`" if r else "—")
        A(f"| `{model.split('/')[-1]}` | " + " | ".join(cells) + " | MEASURED |")
    A("")
    # Counted, not asserted: an earlier draft claimed "every failure", which
    # the data does not support — one deepseek failure landed in sharp_selloff.
    fails = [(r["model"], r["regime"], r["attempts"] - r["n_usable"])
             for r in probe["rows"] if r["n_usable"] < r["attempts"]
             and r["model"] != DEAR]
    n_fail = sum(f for _m, _r, f in fails)
    n_flat = sum(f for _m, reg, f in fails if reg == "flat_range")
    A(f"Failures concentrate heavily in `flat_range` — `{n_flat}` of the "
      f"`{n_fail}` failures across the two cheaper models [MEASURED] — the "
      f"regime where nothing obvious should be done. Not exclusively: one "
      f"deepseek failure landed in `sharp_selloff` [MEASURED]. But the "
      f"mid-tier model handles `flat_range` `4/4`, so this is not \"the flat "
      f"tape is hard for everyone\"; it is the cheaper models degrading "
      f"where the judgement is hardest and the correct answer least obvious.")
    A("")
    A("That matters more than the pooled rate. A model that fails randomly "
      "loses decisions at its error rate. A model that fails specifically when "
      "the market is directionless loses them in clusters, and on a flat day "
      "loses most of them.")
    A("")

    unm = probe.get("_unmeasured", {})
    if unm:
        A("### Not measured, and why")
        A("")
        for model, info in unm.items():
            A(f"- **`{model}`** — {info['reason']} [NOT MEASURED]")
            A(f"  {info['note']} [MEASURED]")
        A("")

    # ------------------------------------------------------------- D2 ------
    A("## End-to-end projection")
    A("")
    A("Routing keeps the decision step on the expensive model by design, so "
      "the fraction of a bill it can touch is the MECHANICAL steps' share of "
      "pipeline cost — computed from measured tokens, never assumed to be "
      "everything.")
    A("")

    configs = []
    for dec_model in (MID, DEAR):
        p = re_.endtoend_projection(MID, CHEAP, decision_model=dec_model)
        configs.append((dec_model, p))

    A("| decision model kept | mechanical share | end-to-end saving | completion | floor | Tier |")
    A("|---|---:|---:|---:|---:|---|")
    for dec_model, p in configs:
        A(f"| `{dec_model.split('/')[-1]}` | "
          f"`{p['mechanical_share_of_baseline'].value:.1%}` | "
          f"**`{p['saving_fraction'].value:.1%}`** | "
          f"`{p['routed_completion'].value:.1%}` | "
          f"`{p['routed_completion_floor'].value:.1%}` | DERIVED |")
    A("")
    A("**The headline is `35.6%`, not `76.2%`** [DERIVED]. Phase 16's `76.2%` "
      "was the saving on the mechanical steps in isolation and was correctly "
      "labelled as such; applied end to end it roughly halves, because those "
      "steps are only `49.4%` of pipeline cost [DERIVED].")
    A("")
    A("**And it gets smaller the better the model you protect.** Keeping the "
      "mid-tier model on the decision step puts `76.7%` of pipeline cost "
      "beyond routing's reach, leaving `15.5%` [DERIVED]. The lever is "
      "strongest exactly when the thing it protects is cheap — which is the "
      "opposite of when you need it.")
    A("")

    mid_p = configs[0][1]
    A("### The compound effect, measured, running backwards")
    A("")
    A(f"Later prompts embed every prior output verbatim, so a terser step-1 "
      f"model shrinks downstream input. The obvious assumption is that the "
      f"cheap model is terser. It is not: `{CHEAP.split('/')[-1]}` emits "
      f"`1,458` output tokens at step 1 against `1,197` [MEASURED], so routing "
      f"**inflates** the decision step's input.")
    A("")
    A("| | baseline | routed | Tier |")
    A("|---|---:|---:|---|")
    A(f"| decision-step input tokens | "
      f"`{mid_p['baseline_rows'][-1]['input_tokens']:,.0f}` | "
      f"`{mid_p['routed_rows'][-1]['input_tokens']:,.0f}` | MEASURED |")
    A(f"| decision-step cost | "
      f"`${mid_p['baseline_rows'][-1]['cost_usd']:.6f}` | "
      f"`${mid_p['routed_rows'][-1]['cost_usd']:.6f}` | DERIVED |")
    A("")
    A("The step routing was meant to protect gets **more expensive** under "
      "routing [DERIVED]. The `35.6%` above is net of that penalty, not before "
      "it.")
    A("")

    A("### Completion is bounded, not known")
    A("")
    n_dec = probe["summary"][0]["n_total"]
    A(f"`pipeline_runner` aborts the whole decision on any unparseable step "
      f"with no retry, so completion is the product of the per-step rates. The "
      f"floor column applies the rule of three to every observation that came "
      f"back perfect: `{n_dec}/{n_dec}` bounds a failure rate at "
      f"`{rule_of_three_upper_bound(n_dec):.0%}`, not at zero [DERIVED]. A "
      f"completion figure built from three such observations has a floor of "
      f"`{mid_p['routed_completion_floor'].value:.0%}` — and at `156` "
      f"decisions/day the distance between the point estimate and that floor "
      f"is the difference between a working product and a broken one.")
    A("")

    A("### Against each cadence")
    A("")
    sav = re_.saving_against_cadence(mid_p, CADENCE_BILLS)
    A("| cadence | monthly bill | routing saving | Tier |")
    A("|---|---:|---:|---|")
    for name, bill in CADENCE_BILLS.items():
        A(f"| {name} | `${bill:,.0f}` | WITHHELD | DERIVED |")
    A("")
    A(f"**Withheld deliberately.** {sav['refused']} [NOT MEASURED]")
    A("")
    A("The seed leaderboard runs measured `1.000` calls per decision "
      "[MEASURED] — single-prompt agents with no mechanical steps at all. "
      "Routing would have saved them exactly nothing. Until the multi-step "
      "share of spend is known, a saving applied to a whole bill would be "
      "an assumption wearing a measurement's clothes.")
    A("")

    A("## What is still not measured")
    A("")
    A("**Whether routing changes the decision step's RELIABILITY** "
      "[NOT MEASURED]. The table above shows identical completion for baseline "
      "and routed, and that is an artifact, not a finding: every decision-step "
      "attempt in this probe read upstream produced by the CHEAP model, "
      "because that is the routed configuration. There is no measurement of "
      "the decision step reading expensive upstream, so the two arms carry the "
      "same rate by construction. Closing it means re-running the probe with "
      "the expensive model upstream and comparing — roughly the same cost "
      "again.")
    A("")
    A("**Whether routing changes WHICH decisions are made** [NOT MEASURED]. "
      "This probe establishes that the decision step still parses; it says "
      "nothing about whether the orders are the same, or as good. That needs "
      "multiple evaluation windows and a definition of \"same\", and four "
      "regimes in one run cannot support it. It is out of scope here and it is "
      "the question that should gate adoption.")
    A("")
    A("Everything above is a cost and reliability result. None of it is a "
      "quality result.")
    A("")
    return "\n".join(L) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    text = build()
    result = check_report(text)
    if not result["ok"]:
        print(f"UNTAGGED NUMERIC LINES ({result['n_violations']}):",
              file=sys.stderr)
        print(format_violations(result["violations"]), file=sys.stderr)
        return 3
    if args.check:
        print(f"[check] builds, {len(text.splitlines())} lines, all tagged")
        return 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"[report] {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
