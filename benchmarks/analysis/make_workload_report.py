#!/usr/bin/env python3
"""Generate WORKLOAD_AND_API_CEILING.md from the measured inputs.

    python benchmarks/analysis/make_workload_report.py --check
    python benchmarks/analysis/make_workload_report.py

Every number in the output is produced here from ``load_measured`` and the
committed sweep results, so the document cannot drift from the data. A
staleness test regenerates it and compares byte-for-byte.
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Any, Dict, List, Optional

_HERE = os.path.dirname(os.path.abspath(__file__))
_BENCH_ROOT = os.path.abspath(os.path.join(_HERE, ".."))
if _BENCH_ROOT not in sys.path:
    sys.path.insert(0, _BENCH_ROOT)

from analysis import api_optimisation as ao            # noqa: E402
from analysis import workload_split as ws              # noqa: E402
from analysis.cost_model_lib import load_measured      # noqa: E402
from analysis.tier_check import check_report, format_violations  # noqa: E402

DEFAULT_OUT = os.path.join(_HERE, "WORKLOAD_AND_API_CEILING.md")
SWEEP = os.path.join(_BENCH_ROOT, "results", "output_cap_sweep.json")

CHEAP = "nvidia/nemotron-3-nano-30b-a3b"
DEAR = "deepseek/deepseek-v4-pro"

# The experiment scenario the report is built around. Stated here rather than
# buried, because every experiment figure is conditional on it.
EXPERIMENT_SCENARIO = {
    "n_agents": 1000,
    "n_distinct_models": 7,
    "calls_per_decision": 1,
    "experiment_duration_days": 30,
}


def _pct(x: Optional[float]) -> str:
    return "—" if x is None else f"{x:.1%}"


def build(measured: Optional[Dict[str, Any]] = None) -> str:
    measured = measured or load_measured()
    models = list(measured["models"])
    L: List[str] = []
    A = L.append

    A("# Two workloads, and how far the API bill can be pushed")
    A("")
    A("Generated by `analysis/make_workload_report.py`. Every figure is "
      "computed from measured per-call costs (verified against stored "
      "`est_cost_usd` to `<1e-5`) [MEASURED] or refuses to compute.")
    A("")

    # ---------------------------------------------------------------- D1 ----
    A("## Why the $50K figure never pinned down")
    A("")
    A("ATL has two cost workloads with different controllability, and every "
      "prior model mixed them.")
    A("")
    A("| | EXPERIMENT | USER PLATFORM |")
    A("|---|---|---|")
    A("| who sets the volume | the lab | signups |")
    A("| cadence | a design choice | follows the product |")
    A("| model set | **the independent variable** | the user's dropdown pick |")
    A("| bounded by | design | nothing |")
    A("| can you skip bars to save money | yes | no — it looks broken |")
    A("")

    hourly = ws.experiment_cost(
        {**EXPERIMENT_SCENARIO, "cadence_seconds": 3600, "models": models},
        measured)
    nof1 = ws.experiment_cost(
        {**EXPERIMENT_SCENARIO, "cadence_seconds": 150, "models": models},
        measured)
    ratio = nof1["total_cost_usd"].value / hourly["total_cost_usd"].value

    A("### The 22x that changed underneath every earlier figure")
    A("")
    A(f"Target cadence is Nof1's 2-3 minutes, not hourly. For "
      f"`{EXPERIMENT_SCENARIO['n_agents']}` agents over "
      f"`{EXPERIMENT_SCENARIO['experiment_duration_days']}` days, an even "
      f"split across all seven models [DERIVED]:")
    A("")
    A("| cadence | decisions/agent/day | calls/day | 30-day cost | Tier |")
    A("|---|---:|---:|---:|---|")
    A(f"| hourly (3600s) | `{hourly['decisions_per_agent_day'].value:.1f}` | "
      f"`{hourly['calls_per_day'].value:,.0f}` | "
      f"`${hourly['total_cost_usd'].value:,.0f}` | DERIVED |")
    A(f"| Nof1 (150s) | `{nof1['decisions_per_agent_day'].value:.1f}` | "
      f"`{nof1['calls_per_day'].value:,.0f}` | "
      f"`${nof1['total_cost_usd'].value:,.0f}` | DERIVED |")
    A("")
    A(f"A `{ratio:.0f}x` change [DERIVED]. Nothing else in either model moves "
      f"cost by that much, which is why both are carried side by side rather "
      f"than the old figures being replaced.")
    A("")

    A("### EXPERIMENT — every parameter is a lever, except one")
    A("")
    A("| parameter | control | may be optimised? |")
    A("|---|---|---|")
    for p in ws.EXPERIMENT_PARAMS.values():
        A(f"| `{p.name}` | {p.control} | "
          f"{'**NO — the independent variable**' if p.required_by_experiment else 'yes'} |")
    A("")
    A("Model diversity **is** Experiment C's independent variable. Correlated "
      "failure across models cannot be measured with fewer models; reducing it "
      "does not make the experiment cheaper, it makes it a different "
      "experiment. Agent count, cadence and duration are power and design "
      "choices — nothing in the NVIDIA note fixes them.")
    A("")

    sens = ws.experiment_sensitivity(
        {**EXPERIMENT_SCENARIO, "cadence_seconds": 150, "models": models},
        measured)
    A("Sensitivity, doubling each parameter [DERIVED]:")
    A("")
    A("| parameter | cost ratio | may be optimised? |")
    A("|---|---:|---|")
    for r in sens:
        A(f"| `{r['parameter']}` | `{r['cost_ratio']:.2f}x` | "
          f"{'**NO**' if r['required_by_experiment'] else 'yes'} |")
    A("")
    A("The ranking is not a to-do list. The largest term is the one that may "
      "not be touched.")
    A("")

    # --- the power question ---
    pq = ws.power_question_options(measured, duration_days=30)
    A("### The question nobody has asked")
    A("")
    A("> Does measuring correlated failure need a thousand agents at "
      "two-minute cadence across the full model roster, or would a smaller "
      "population, a slower cadence, or fewer models give adequate "
      "statistical power?")
    A("")
    A("**This is not answered here** and cannot be: required power depends on "
      "the effect size sought, which nobody has stated [NOT MEASURED]. What "
      "follows prices the options so the question can be asked with numbers "
      "attached.")
    A("")
    A("| option | 30-day cost | vs full | changes the experiment? | Tier |")
    A("|---|---:|---:|---|---|")
    for o in pq["options"]:
        cost = (f"`${o['cost_usd']:,.0f}`" if o["cost_usd_high"] is None
                else f"`${o['cost_usd']:,.0f}` – `${o['cost_usd_high']:,.0f}`")
        A(f"| {o['option']} | {cost} | `{o['ratio_to_full']:.2f}x` | "
          f"{'**yes**' if o['destroys_experiment'] else 'no'} | DERIVED |")
    A("")
    three = [o for o in pq["options"] if o["n_models"] == 3][0]
    A(f"**Fewer models is a range, not a saving.** Which models are dropped "
      f"matters more than how many: the same \"3 models\" spans "
      f"`${three['cost_usd']:,.0f}` to `${three['cost_usd_high']:,.0f}` "
      f"[DERIVED]. Dropping the *cheap* models costs more than keeping all "
      f"seven, because it raises the blended rate.")
    A("")

    # --- platform ---
    A("### PLATFORM — cost follows signups")
    A("")
    A("| parameter | control |")
    A("|---|---|")
    for p in ws.PLATFORM_PARAMS.values():
        A(f"| `{p.name}` | {p.control} |")
    A("")
    A("The lab's levers are narrower than the parameter list suggests:")
    A("")
    for lever in ws.PLATFORM_LEVERS:
        A(f"- {lever}")
    A("")
    plat_sens = ws.platform_sensitivity(
        {"n_users": 1000, "agents_per_user": 2,
         "backtests_per_user_per_day": 1.0,
         "model_mix": {"nemotron_3_nano_30b": 1.0},
         "pipeline_depth_distribution": {1: 1.0},
         "live_trading_on": True, "cadence_seconds": 150,
         "bars_per_backtest": 161}, measured)
    A("Sensitivity, doubling each [DERIVED]:")
    A("")
    A("| parameter | cost ratio | a lever? |")
    A("|---|---:|---|")
    for r in plat_sens:
        A(f"| `{r['parameter']}` | `{r['cost_ratio']:.2f}x` | "
          f"{'yes' if r['is_lever'] else 'no'} |")
    A("")
    A("Dropdown composition is the only platform term above `2x` [DERIVED], "
      "and it is the one thing on the list the lab partly controls.")
    A("")

    # --- leaderboard ---
    lb = ws.leaderboard_recurring(measured)
    A("### LEADERBOARD — neither workload")
    A("")
    A(f"**Recurring cost today is `$0`** [MEASURED], and that is a fact about "
      f"the repository rather than an estimate: `refresh_daily_leaderboard.py` "
      f"states in its own docstring that *\"nothing in this repo runs this "
      f"script automatically yet — there is no cron or CI schedule wired up\"*, "
      f"and redeploying LLM entries sits behind an explicit `--models` flag.")
    A("")
    A(f"What exists is a one-off: `${lb['contest_window']['cost_usd'].value:,.2f}` "
      f"per manual full deploy — 7 models over the 161-bar contest window "
      f"[MEASURED].")
    A("")
    A("The *daily* board is a rolling **one-day** window, not the month-long "
      "contest window. Its recurring figure is deliberately not computed: at "
      "hourly cadence that day holds ~7 bars, at Nof1 ~156, and those differ "
      "by `22x` [DERIVED]. Supplying a bar count produces it.")
    A("")

    # ---------------------------------------------------------------- D2 ----
    A("## How far the API bill can be pushed")
    A("")
    A("Four levers, each measured for cost *and* for what it does to "
      "behaviour. The decision model never changes.")
    A("")

    steps = ao.load_step_measurements()
    routing = ao.routing_projection(DEAR, CHEAP, steps, measured)

    A("### 2a — per-step routing")
    A("")
    A(f"Routing the mechanical steps from `{DEAR}` to `{CHEAP}`, on measured "
      f"token counts:")
    A("")
    A("| | baseline | routed | Tier |")
    A("|---|---:|---:|---|")
    A(f"| cost per decision (steps 1-2) | "
      f"`${routing['baseline_cost_usd'].value:.6f}` | "
      f"`${routing['routed_cost_usd'].value:.6f}` | DERIVED |")
    A(f"| saving | | `{_pct(routing['saving_fraction'].value)}` | DERIVED |")
    A("")
    ce = routing["compound_effect"]
    A(f"**The compound effect runs backwards.** The obvious assumption is that "
      f"a cheap model is terser and shrinks every later step's input. Measured, "
      f"it is the opposite: `{CHEAP}` emits "
      f"`{ce['step1_output_cheap']:.0f}` output tokens at step 1 against "
      f"`{ce['step1_output_baseline']:.0f}` for `{DEAR}` [MEASURED], and "
      f"`_build_step_prompt` embeds that verbatim in every later prompt. "
      f"Routing step 1 to the cheaper model **inflates** downstream input.")
    A("")
    pr = routing["parse_rates"]
    A(f"**The parse rates do not support deployment.** Every measured cell was "
      f"`{pr['n_per_cell']}/{pr['n_per_cell']}` [MEASURED], which by the rule "
      f"of three bounds the per-step failure rate at "
      f"`{pr['upper_bound_failure_rate_95pct']:.1%}` at 95% confidence — not "
      f"at zero [DERIVED]. At `156` decisions/day that ceiling is far too "
      f"loose to act on; it needs hundreds of attempts per cell, not fifteen.")
    A("")
    A(f"**No end-to-end saving is stated.** The decision step's parse rate is "
      f"unmeasured — both models scored `0/15` there against a content-free "
      f"fixture because of the empty-orders defect, which measures the "
      f"pipeline and not the model [MEASURED]. Without it there is no "
      f"completion rate, and a saving without a completion rate is not a "
      f"result.")
    A("")

    # --- 2b ---
    A("### 2b — output token caps")
    A("")
    A("Output is priced ~`4x` input and the structure inverts across the "
      "roster [MEASURED]:")
    A("")
    drop = ao.dropdown_composition(measured)
    A("| model | $/call | input share | output share | out tokens | Tier |")
    A("|---|---:|---:|---:|---:|---|")
    for r in drop["rows"]:
        A(f"| `{r['model']}` | `${r['cost_per_call_usd']:.6f}` | "
          f"`{1 - r['output_share_of_cost']:.1%}` | "
          f"`{r['output_share_of_cost']:.1%}` | "
          f"`{r['output_tokens_per_call']:,.0f}` | MEASURED |")
    A("")
    A("The driver is output **volume**, not tier: input spans `3,895`–`5,502` "
      "tokens per call across the roster while output spans `860`–`5,005` "
      "[MEASURED]. The verbose models happen to be the expensive ones.")
    A("")

    if os.path.exists(SWEEP):
        caps = ao.cap_projection(sweep_path=SWEEP, measured=measured)
        A(f"Measured sweep, `{caps['attempts_per_cell']}` attempts per cell:")
        A("")
        A("| model | step | cap | mean out | token reduction | parse | verdict | Tier |")
        A("|---|---:|---:|---:|---:|---:|---|---|")
        import json as _json
        with open(SWEEP, "r", encoding="utf-8") as fh:
            raw_rows = _json.load(fh)["rows"]
        for row in raw_rows:
            base = max(r["mean_output_tokens"] or 0 for r in raw_rows
                       if r["model"] == row["model"]
                       and r["step_index"] == row["step_index"])
            red = 1 - (row["mean_output_tokens"] or 0) / base if base else 0
            verdict = "safe" if row["parse_rate"] == 1.0 else "**breaks**"
            A(f"| `{row['model'].split('/')[-1]}` | {row['step_index'] + 1} | "
              f"`{row['max_tokens']}` | `{row['mean_output_tokens'] or 0:,.0f}` | "
              f"`{red:.1%}` | `{row['parse_rate']:.0%}` | {verdict} | MEASURED |")
        A("")
        for r in caps["results"]:
            A(f"- `{r['model'].split('/')[-1]}`: lowest safe cap "
              f"`{r['lowest_safe_cap']}`, max safe token reduction "
              f"`{r['max_safe_token_reduction']:.1%}` [MEASURED]")
        A("")
        A("**A cap only saves where it binds, and breaks where it bites.** A "
          "cap above a step's natural output length costs nothing and saves "
          "nothing; below it the JSON truncates and the decision aborts with "
          "no retry. Every safe row above is a cap that never bound — the "
          "small non-zero reductions on those rows are run-to-run variation in "
          "how much the model chose to write, not an effect of the cap "
          "[MEASURED]. Hence `0.0%` max safe reduction for both models.")
        A("")
        A("**So 2b is a dead end as measured.** There is no cap that both "
          "binds and survives. Step 2 emits ~`300` tokens naturally, so any "
          "cap that would save anything there is already below the break "
          "point; step 1 emits ~`1,300` and collapses the moment a cap "
          "reaches it [MEASURED]. The lever attacks the right cost term and "
          "has nowhere to stand.")
        A("")
        A("One mechanism is worth recording: at tight caps the dominant "
          "failure is `empty`, not `truncated`. Both models are reasoning "
          "models, so a small budget is consumed by thinking tokens and no "
          "answer text is emitted at all [MEASURED].")
        A("")
    else:
        A("**No sweep committed** — `results/output_cap_sweep.json` is absent, "
          "so no cap saving is stated [NOT MEASURED]. Run "
          "`analysis/output_cap_sweep.py`.")
        A("")

    # --- 2c ---
    elim = ao.eliminated_calls(measured)
    A("### 2c — eliminated calls")
    A("")
    A("The only lever with no behaviour cost: a cache hit returns the "
      "identical stored result, faster.")
    A("")
    A("**Backtest caching cannot be sized.** A cache saves exactly the repeat "
      "rate and nothing else, and no telemetry records how often users re-run "
      "an identical backtest [NOT MEASURED]. An assumed rate here would put an "
      "invented number at the centre of the saving, so it is refused.")
    A("")
    A(f"**Leaderboard governance saves `$0` recurring** [MEASURED], because "
      f"nothing is scheduled to run. It prevents future recurring cost if a "
      f"scheduler is added; claiming a saving against a schedule that does not "
      f"exist would be counting money nobody is spending.")
    A("")

    # --- 2d ---
    A("### 2d — dropdown composition (not an engineering change)")
    A("")
    A(f"Models users cannot select cost nothing. The measured span is "
      f"`{drop['span'].value:,.0f}x` [MEASURED] — see the table in 2b for the "
      f"per-model figures.")
    A("")
    A("This is the advisor's call, not an engineering change. What it costs "
      "in capability is unknown: one evaluation window could not establish "
      "that the expensive models trade better (Spearman rho `+0.071`, "
      "intervals overlapping) [MEASURED].")
    A("")

    # --- stacked ---
    A("### The stacked ceiling, and what it leaves")
    A("")
    if os.path.exists(SWEEP):
        stacked = ao.stacked_ceiling(routing, caps, monthly_bill_usd=600_000)
        A(f"Caps contribute nothing, so the stack is routing alone: "
          f"`{_pct(stacked['stacked_saving_fraction'].value)}` [DERIVED] — and "
          f"that is an upper bound that overstates, for the reasons below.")
        A("")
        A(f"Applied to a `$600,000`/month all-seven-models Nof1 figure it "
          f"would leave `${stacked['residual_usd_per_month'].value:,.0f}`/month "
          f"[DERIVED]. **Read that as a floor on what is left, not a forecast.**")
        A("")
        for n in stacked["notes"]:
            A(f"- {n}")
        A(f"- {stacked['overlap_warning']}")
        A("")
    A("**Only model choice reaches the right order of magnitude.** Every "
      "engineering lever put together is well under `3x`; the per-call span "
      "across the roster is `193x` [MEASURED]. A 60-70% reduction on a "
      "$600k/month bill is still ~$200k/month. The decision that changes the "
      "order of magnitude is which models are offered at all — which is the "
      "same decision as open-weight substitution, and it rests on evidence "
      "that does not exist yet.")
    A("")

    A("## What is deliberately not modelled")
    A("")
    A("- **Prefix caching.** Measured at zero cached tokens over `160` "
      "requests against a `99.4%` shared-prefix fixture, `stats_source` null "
      "on both vLLM builds tested [MEASURED]. No saving modelled.")
    A("- **Sampling, staggering, skipping bars.** Experiment-only. On a user's "
      "agent it is indistinguishable from the product being broken.")
    A("- **Self-hosting.** A separate experiment in different units.")
    A("- **Any fallback-rate adjustment.** Unrecoverable from stored data in "
      "either direction.")
    A("")
    return "\n".join(L) + "\n"


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    text = build()
    result = check_report(text)
    if not result["ok"]:
        print(f"UNTAGGED NUMERIC LINES ({result['n_violations']}):",
              file=sys.stderr)
        print(format_violations(result["violations"]), file=sys.stderr)
        return 3
    if args.check:
        print(f"[check] builds, {len(text.splitlines())} lines, all tagged")
        return 0
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"[report] {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
